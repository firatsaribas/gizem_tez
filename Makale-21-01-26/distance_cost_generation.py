# =============================================================================
# PARAMETERS  — edit these as needed
# =============================================================================

FUEL_CONSUMPTION_PER_100KM = 12     # litres / 100 km
FUEL_PRICE_PER_LITRE       = 1.29   # EUR / litre
DIVISOR                    = 245    # cost divisor

OUTPUT_FILE = "distance_cost_matricessample1.xlsx"

# =============================================================================
# COMPUTE MATRICES
# =============================================================================

df = pd.DataFrame(data, columns=["ID", "Lat", "Lon"])
ids = df["ID"].tolist()
n   = len(ids)

print(f"Computing {n}x{n} matrices for {n} points...")

dist_matrix = [[0.0] * n for _ in range(n)]
cost_matrix = [[0.0] * n for _ in range(n)]

for i in range(n):
    for j in range(n):
        if i != j:
            p1  = (df.iloc[i]["Lat"], df.iloc[i]["Lon"])
            p2  = (df.iloc[j]["Lat"], df.iloc[j]["Lon"])
            d   = geodesic(p1, p2).km
            fuel_cost = (d * (FUEL_CONSUMPTION_PER_100KM / 100) * FUEL_PRICE_PER_LITRE) / DIVISOR
            dist_matrix[i][j] = round(d, 4)
            cost_matrix[i][j] = round(fuel_cost, 6)

    if (i + 1) % 20 == 0 or (i + 1) == n:
        print(f"  {i + 1}/{n} rows done...")

# =============================================================================
# WRITE TO EXCEL
# =============================================================================

def apply_header_style(cell):
    cell.font      = Font(bold=True, color="FFFFFF", name="Arial", size=9)
    cell.fill      = PatternFill("solid", start_color="1F4E79", end_color="1F4E79")
    cell.alignment = Alignment(horizontal="center", vertical="center")

def write_matrix_sheet(wb, sheet_name, matrix, ids, title):
    ws = wb.create_sheet(sheet_name)
    n  = len(ids)

    thin_side   = Side(style="thin", color="BFBFBF")
    thin_border = Border(left=thin_side, right=thin_side,
                         top=thin_side, bottom=thin_side)
    diag_fill   = PatternFill("solid", start_color="D9D9D9", end_color="D9D9D9")
    data_font   = Font(name="Arial", size=8)
    center      = Alignment(horizontal="center", vertical="center")

    # Title
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=n + 1)
    ws["A1"]           = title
    ws["A1"].font      = Font(bold=True, name="Arial", size=11)
    ws["A1"].alignment = Alignment(horizontal="center")
    ws.row_dimensions[1].height = 18

    # Column header row
    corner = ws.cell(row=2, column=1, value="FROM \\ TO")
    apply_header_style(corner)
    ws.row_dimensions[2].height = 14

    for j, id_ in enumerate(ids):
        apply_header_style(ws.cell(row=2, column=j + 2, value=id_))

    # Data rows
    for i, row_id in enumerate(ids):
        apply_header_style(ws.cell(row=i + 3, column=1, value=row_id))
        ws.row_dimensions[i + 3].height = 12

        for j, val in enumerate(matrix[i]):
            cell            = ws.cell(row=i + 3, column=j + 2, value=val)
            cell.font       = data_font
            cell.alignment  = center
            cell.border     = thin_border
            if i == j:
                cell.fill   = diag_fill

    # Column widths
    ws.column_dimensions["A"].width = 8
    for j in range(n):
        ws.column_dimensions[get_column_letter(j + 2)].width = 7

    ws.freeze_panes = "B3"


wb = Workbook()
wb.remove(wb.active)  # remove default blank sheet

write_matrix_sheet(
    wb,
    "Distance Matrix (km)",
    dist_matrix, ids,
    "Distance Matrix (km)  —  Geodesic via geopy"
)

write_matrix_sheet(
    wb,
    "Cost Matrix (EUR)",
    cost_matrix, ids,
    f"Cost Matrix (EUR)  |  {FUEL_CONSUMPTION_PER_100KM} L/100km  ×  {FUEL_PRICE_PER_LITRE} EUR/L  ÷  {DIVISOR}"
)

# Assumptions sheet
ws_a = wb.create_sheet("Assumptions")
headers = ["Parameter", "Value", "Unit"]
for col, h in enumerate(headers, start=1):
    cell      = ws_a.cell(row=1, column=col, value=h)
    cell.font = Font(bold=True, name="Arial")

assumptions = [
    ("Fuel Consumption",  FUEL_CONSUMPTION_PER_100KM, "L / 100 km"),
    ("Fuel Price",        FUEL_PRICE_PER_LITRE,        "EUR / L"),
    ("Divisor",           DIVISOR,                     "-"),
    ("Distance Method",   "geodesic (geopy)",          "-"),
    ("Total Points",      n,                           "-"),
]
for r, (param, val, unit) in enumerate(assumptions, start=2):
    ws_a.cell(row=r, column=1, value=param).font = Font(name="Arial")
    ws_a.cell(row=r, column=2, value=val   ).font = Font(name="Arial")
    ws_a.cell(row=r, column=3, value=unit  ).font = Font(name="Arial")

ws_a.column_dimensions["A"].width = 24
ws_a.column_dimensions["B"].width = 20
ws_a.column_dimensions["C"].width = 16

wb.save(OUTPUT_FILE)
print(f"\nDone! Saved to: {OUTPUT_FILE}")